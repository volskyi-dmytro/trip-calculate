type Dictionary = Record<Language, Record<string, string>>;

export const PLURAL_SUFFIX = /_(zero|one|two|few|many|other)$/;

export const pluralKey = (key: string, category: Intl.LDMLPluralRule) => `${key}_${category}`;

// Ukrainian first, then English, and the bare key only when neither has it,
// so a missing translation degrades to English instead of `dashboard.foo`.
export function translate(language: Language, key: string, dict: Dictionary = translations): string {
  const value = dict[language][key] ?? dict.en[key];
  if (value === undefined && import.meta.env.DEV) {
    console.warn(`[i18n] missing key: ${key}`);
  }
  return value ?? key;
}

// Chooses the CLDR plural form (uk: one/few/many/other) and fills `{count}`.
export function translatePlural(
  language: Language,
  key: string,
  count: number,
  dict: Dictionary = translations,
): string {
  const category = new Intl.PluralRules(language).select(count);
  const template = dict[language][pluralKey(key, category)] !== undefined
    ? translate(language, pluralKey(key, category), dict)
    : translate(language, pluralKey(key, 'other'), dict);
  return template.replace('{count}', count.toLocaleString(language === 'uk' ? 'uk-UA' : 'en-US'));
}
